#!/usr/bin/env bash
# Generate sources/*.rsp from sources/*.list and tests/*.cs globs (rearch stage 5).
# Called by tools/linux-compile-check.sh. Do not hand-edit the generated .rsp files.
# Generated .rsp are gitignored; always regenerate before compile.
# Sort order for tests/*.cs must match tools/gen-rsp.bat (dir /b /o:n ≈ LC_ALL=C sort).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

if [[ ! -f sources/core.list || ! -f sources/app.list ]]; then
  echo "gen-rsp: missing sources/core.list or sources/app.list" >&2
  exit 1
fi

{
  echo "# GENERATED by tools/gen-rsp - do not edit; change sources/core.list"
  # strip blank lines and comments from the list (preserve list order)
  grep -v '^[[:space:]]*#' sources/core.list | grep -v '^[[:space:]]*$' || true
} > sources/core.rsp

{
  echo "# GENERATED by tools/gen-rsp - do not edit; change sources/app.list"
  grep -v '^[[:space:]]*#' sources/app.list | grep -v '^[[:space:]]*$' || true
} > sources/app.rsp

{
  echo "# GENERATED by tools/gen-rsp - do not edit; add tests/*.cs"
  if compgen -G "tests/*.cs" > /dev/null; then
    # Windows rsp paths use backslash; csc on Windows expects tests\Name.cs
    # LC_ALL=C sort matches gen-rsp.bat dir /b /o:n for ASCII SelfTest.*.cs names.
    LC_ALL=C find tests -maxdepth 1 -type f -name '*.cs' -printf '%f\n' | LC_ALL=C sort | while IFS= read -r base; do
      printf 'tests\\%s\n' "$base"
    done
  fi
} > sources/selftest.rsp

exit 0
